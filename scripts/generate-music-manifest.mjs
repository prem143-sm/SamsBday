// Scans public/music/<playlist> folders and regenerates src/data/music-manifest.ts.
// Run with: npm run music:scan  (also runs automatically before every build).
// Add real audio files to the folders below, then re-run to refresh the manifest.
import { promises as fs } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const musicRoot = path.join(root, 'public', 'music');
const output = path.join(root, 'src', 'data', 'music-manifest.ts');

// Audio formats the browser can usually decode. FLAC is included but only plays
// where the browser supports it (e.g. Chrome/Edge/Firefox); missing/unsupported
// files are skipped gracefully at playback time.
const supportedExtensions = ['.mp3', '.m4a', '.wav', '.ogg', '.flac'];

// The two fixed playlists. `name` is the exact label shown in the UI.
const playlists = [
  { id: 'sams-playlist', name: "Sam's Playlist", folder: 'Sams-Playlist' },
  { id: 'prems-playlist', name: "Prem's Playlist", folder: 'Prems-Playlist' },
];

const extensionOf = (filename) => path.extname(filename).toLowerCase();

// Turn a filename into a readable title without inventing metadata.
// "01 - Tum Hi Ho.mp3" -> "Tum Hi Ho", "my_song.flac" -> "my song".
const toTitle = (filename) => {
  const withoutExtension = path.basename(filename, path.extname(filename));
  const withoutLeadingNumber = withoutExtension.replace(/^\s*\d+\s*[-._)]+\s*/, '');
  const spaced = (withoutLeadingNumber || withoutExtension)
    .replace(/[_-]+/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
  return spaced || withoutExtension.trim();
};

// Stable, URL-safe id derived from the filename (independent of track order).
const slugify = (value) => value
  .toLowerCase()
  .replace(/[^a-z0-9]+/g, '-')
  .replace(/^-+|-+$/g, '') || 'track';

async function readTracks(playlist) {
  const folderPath = path.join(musicRoot, playlist.folder);
  let entries;
  try {
    entries = await fs.readdir(folderPath, { withFileTypes: true });
  } catch (error) {
    if (error.code === 'ENOENT') return [];
    throw error;
  }

  const files = entries
    .filter((entry) => entry.isFile() && supportedExtensions.includes(extensionOf(entry.name)))
    .map((entry) => entry.name)
    .sort((left, right) => left.localeCompare(right, undefined, { numeric: true, sensitivity: 'base' }));

  const usedIds = new Set();
  return files.map((filename, index) => {
    let id = `${playlist.id}-${slugify(path.basename(filename, path.extname(filename)))}`;
    let suffix = 2;
    while (usedIds.has(id)) id = `${playlist.id}-${slugify(path.basename(filename, path.extname(filename)))}-${suffix++}`;
    usedIds.add(id);

    // Encode one URL path segment safely. `encodeURIComponent` over-escapes
    // characters that are legal (and expected) inside a path segment — such as
    // , & @ ( ) ! ' * — which makes the static server fail to match the file
    // on disk (404 → SPA fallback). We re-allow the RFC 3986 "sub-delims" plus
    // ':' and '@' so the URL round-trips to the real filename, while spaces,
    // '#', '?', '%' and non-ASCII stay percent-encoded.
    const safeInPath = "!$&'()*+,;=:@";
    const encodeSegment = (value) => encodeURIComponent(value).replace(
      new RegExp(`%(${[...safeInPath].map((c) => c.charCodeAt(0).toString(16).toUpperCase().padStart(2, '0')).join('|')})`, 'g'),
      (_, hex) => String.fromCharCode(parseInt(hex, 16)),
    );
    const url = `/music/${encodeSegment(playlist.folder)}/${encodeSegment(filename)}`;
    return { id, title: toTitle(filename), url, order: index + 1 };
  });
}

const manifest = [];
for (const playlist of playlists) {
  const tracks = await readTracks(playlist);
  manifest.push({ id: playlist.id, name: playlist.name, folder: playlist.folder, tracks });
}

const content = `// Generated by scripts/generate-music-manifest.mjs. Do not edit by hand.
// Add audio files to public/music/Sams-Playlist or public/music/Prems-Playlist, then run: npm run music:scan

export interface MusicTrack {
  id: string;
  title: string;
  url: string;
  order: number;
}

export interface MusicPlaylist {
  id: string;
  name: string;
  folder: string;
  tracks: MusicTrack[];
}

export const musicPlaylists: MusicPlaylist[] = ${JSON.stringify(manifest, null, 2)};
`;

await fs.mkdir(path.dirname(output), { recursive: true });
await fs.writeFile(output, content, 'utf8');

const total = manifest.reduce((sum, playlist) => sum + playlist.tracks.length, 0);
for (const playlist of manifest) {
  console.log(`  ${playlist.name} (public/music/${playlist.folder}): ${playlist.tracks.length} track(s)`);
}
console.log(`Generated ${path.relative(root, output)} with ${total} track(s) across ${manifest.length} playlist(s).`);
