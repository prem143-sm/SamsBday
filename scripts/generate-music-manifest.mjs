import { promises as fs } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const musicRoot = path.join(root, 'public', 'music');
const playbackRoot = path.join(musicRoot, '.playback');
const output = path.join(root, 'src', 'data', 'music-library.ts');
const extensions = new Set(['.mp3', '.wav', '.ogg', '.m4a', '.aac', '.flac']);

async function walk(directory) {
  const entries = await fs.readdir(directory, { withFileTypes: true });
  const files = await Promise.all(entries.map(async (entry) => {
    if (entry.name === '.playback') return [];
    const fullPath = path.join(directory, entry.name);
    if (entry.isDirectory()) return walk(fullPath);
    return extensions.has(path.extname(entry.name).toLowerCase()) ? [fullPath] : [];
  }));
  return files.flat();
}

const titleFromFile = (file) => path.basename(file, path.extname(file))
  .replace(/[_-]+/g, ' ')
  .replace(/\s+/g, ' ')
  .trim();

let files = [];
try {
  files = await walk(musicRoot);
} catch (error) {
  if (error.code !== 'ENOENT') throw error;
}

files.sort((a, b) => a.localeCompare(b));
const tracks = [];
for (const [index, file] of files.entries()) {
  const relative = path.relative(musicRoot, file);
  const segments = relative.split(path.sep);
  const folder = segments.length > 1 ? segments.slice(0, -1).join(' / ') : 'Music';
  const artist = segments.length > 1 ? segments[0] : 'Unknown Artist';
  const id = `track-${String(index + 1).padStart(3, '0')}`;
  const extension = path.extname(file).slice(1).toLowerCase();
  // Vite's Windows static server does not reliably serve some Unicode-heavy filenames.
  // Keep the original untouched and create a stable hard-link alias for browser playback.
  const playbackFile = path.join(playbackRoot, `${id}.${extension}`);
  await fs.mkdir(playbackRoot, { recursive: true });
  try { await fs.access(playbackFile); } catch {
    try { await fs.link(file, playbackFile); } catch { await fs.copyFile(file, playbackFile); }
  }
  tracks.push({
    id,
    title: titleFromFile(file),
    artist,
    folder,
    src: `/music/.playback/${id}.${extension}`,
    extension,
  });
}

const content = `// Generated by scripts/generate-music-manifest.mjs. Do not edit manually.\n\n` +
  `export interface Track {\n  id: string;\n  title: string;\n  artist: string;\n  folder: string;\n  src: string;\n  extension: string;\n}\n\n` +
  `export const musicLibrary: Track[] = ${JSON.stringify(tracks, null, 2)};\n`;

await fs.mkdir(path.dirname(output), { recursive: true });
await fs.writeFile(output, content, 'utf8');
console.log(`Generated ${path.relative(root, output)} with ${tracks.length} track(s).`);
