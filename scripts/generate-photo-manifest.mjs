import { promises as fs } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const photosRoot = path.join(root, 'public', 'Photos');
const output = path.join(root, 'src', 'data', 'photo-library.ts');
const supportedExtensions = new Set(['.jpg', '.jpeg', '.png', '.webp', '.gif', '.avif']);

async function walk(directory) {
  const entries = await fs.readdir(directory, { withFileTypes: true });
  const nested = await Promise.all(entries.map(async (entry) => {
    const fullPath = path.join(directory, entry.name);
    if (entry.isDirectory()) return walk(fullPath);
    return supportedExtensions.has(path.extname(entry.name).toLowerCase()) ? [fullPath] : [];
  }));
  return nested.flat();
}

let files = [];
try { files = await walk(photosRoot); } catch (error) { if (error.code !== 'ENOENT') throw error; }
files.sort((left, right) => left.localeCompare(right));
const images = files.map((file) => {
  const relative = path.relative(photosRoot, file).split(path.sep);
  const filename = path.basename(file, path.extname(file));
  return { src: `/Photos/${relative.map(encodeURIComponent).join('/')}`, alt: filename.replace(/[_-]+/g, ' ').trim() };
});
const content = `// Generated by scripts/generate-photo-manifest.mjs. Do not edit manually.\n\n` +
  `export interface GalleryImage {\n  src: string;\n  alt: string;\n}\n\n` +
  `export const photoLibrary: GalleryImage[] = ${JSON.stringify(images, null, 2)};\n`;
await fs.mkdir(path.dirname(output), { recursive: true });
await fs.writeFile(output, content, 'utf8');
console.log(`Generated ${path.relative(root, output)} with ${images.length} supported image(s).`);
